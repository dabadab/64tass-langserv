/**
 * Regenerate src/server/directiveDocs.ts from the 64tass reference manual.
 *
 *   node tools/generate-directive-docs.mjs [path-or-url]
 *
 * The manual is one page, and it documents directives as <dt>syntax<dd>text
 * pairs - several <dt>s may share one <dd>, which is how `.pend` and `.endproc`
 * come to have the same description. Everything is copied ACROSS verbatim rather
 * than summarised: the semantics of a directive cannot be probed from the
 * assembler the way its opcode tables can, so the manual is the source of truth
 * and paraphrasing it would only introduce a second, worse one.
 */
import { writeFileSync } from 'fs';
import { readFileSync } from 'fs';

const SOURCE = process.argv[2] ?? 'https://tass64.sourceforge.net/';
const OUT = new URL('../src/server/directiveDocs.ts', import.meta.url);

const html = SOURCE.startsWith('http')
    ? await (await fetch(SOURCE)).text()
    : readFileSync(SOURCE, 'utf-8');

const unescape = (s) => s
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"').replace(/&hellip;/g, '...').replace(/&minus;/g, '-')
    .replace(/&ndash;/g, '-').replace(/&mdash;/g, '-').replace(/&nbsp;/g, ' ')
    .replace(/&q(uot)?;/g, '"').replace(/&[a-z]+;/g, ' ');

/** Strip tags, keeping paragraph breaks, and undo the manual's hard wrapping. */
function text(fragment, paragraphs = false) {
    let s = fragment.split(/<pre>|<dl/)[0];
    if (paragraphs) s = s.replace(/<\/p>\s*<p>|<p>/g, '\n\n');
    s = unescape(s.replace(/<[^>]+>/g, ''));
    s = s.replace(/[ \t]*\n[ \t]*(?!\n)/g, ' ').replace(/[ \t]{2,}/g, ' ');
    s = s.split('\n').map((line) => line.trim()).join('\n');
    return s.replace(/\n{3,}/g, '\n\n').trim();
}

// Walk <dt>/<dd> in order: consecutive <dt>s all belong to the <dd> after them.
const docs = new Map();
let pending = [];
for (const match of html.matchAll(/<(dt|dd)>([\s\S]*?)(?=<dt>|<dd>|<\/dl>)/g)) {
    const [, tag, body] = match;
    if (tag === 'dt') {
        const name = body.match(/<b>\s*(\.[a-zA-Z]+)\s*<\/b>/);
        if (name) pending.push([name[1].toLowerCase(), text(body)]);
        continue;
    }
    const description = text(body, true);
    for (const [name, syntax] of pending) {
        if (description && !docs.has(name)) docs.set(name, { syntax, description });
    }
    pending = [];
}

const entries = [...docs.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines = [
    '/**',
    ' * Descriptions of the assembler\'s directives.',
    ' *',
    ' * GENERATED by tools/generate-directive-docs.mjs from the 64tass reference',
    ' * manual at https://tass64.sourceforge.net/ - do not edit by hand.',
    ' *',
    ' * The text is the manual\'s own, quoted rather than rewritten. Unlike the opcode',
    ' * and addressing tables, what a directive MEANS cannot be probed from the',
    ' * assembler, so the manual is the only source of truth there is; summarising it',
    ' * would just add a second, less reliable one. The manual is by Soci/Singular,',
    ' * the author of 64tass.',
    ' */',
    '',
    'export interface DirectiveDoc {',
    '    /** How the manual writes the directive\'s syntax. */',
    '    syntax: string;',
    '    /** The manual\'s description, verbatim. */',
    '    description: string;',
    '}',
    '',
    '/** Keyed by directive name including the leading dot, lowercase. */',
    'export const DIRECTIVE_DOCS: Readonly<Record<string, DirectiveDoc>> = {',
];
for (const [name, { syntax, description }] of entries) {
    const quote = (s) => JSON.stringify(s);
    lines.push(`    ${quote(name)}: { syntax: ${quote(syntax)}, description: ${quote(description)} },`);
}
lines.push('};', '');

writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${entries.length} directives to ${OUT.pathname}`);
